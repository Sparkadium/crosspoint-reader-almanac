def parse(m):
    rows = [r for r in m.strip("\n").split("\n")]
    assert len(rows) == S, f"{len(rows)} rows"
    for r in rows: assert len(r) == S, f"row len {len(r)}: {r!r}"
    return [[1 if c == "X" else 0 for c in r] for r in rows]

def erode(g):
    out = [[0]*S for _ in range(S)]
    for y in range(S):
        for x in range(S):
            if (g[y][x] and y > 0 and g[y-1][x] and y < S-1 and g[y+1][x]
                    and x > 0 and g[y][x-1] and x < S-1 and g[y][x+1]):
                out[y][x] = 1
    return out

def outline(g):
    e = erode(g)
    return [[g[y][x] & ~e[y][x] for x in range(S)] for y in range(S)]

def preview(path, scale=6):
    sq = 25
    img = Image.new("RGB", (8*sq, 4*sq), "white")
    px = img.load()
    order = "PNBRQK"
    def dither_dark(cx, cy):
        for y in range(sq):
            for x in range(sq):
                if x % 3 == 0 and y % 3 == 0:
                    px[cx+x, cy+y] = (0, 0, 0)
    def halo(cx, cy):
        c = sq // 2
        for y in range(sq):
            for x in range(sq):
                if (x-c)**2 + (y-c)**2 <= 132:
                    px[cx+x, cy+y] = (255, 255, 255)
    def blit(cx, cy, grid):
        off = (sq - S)//2
        for y in range(S):
            for x in range(S):
                if grid[y][x]:
                    px[cx+x+off, cy+y+off] = (0, 0, 0)
    # row 0: black pieces on light; row 1: black on dark
    # row 2: white on light;       row 3: white on dark
    for i, k in enumerate(order):
        g = parse(MASKS[k]); o = outline(g)
        for row in range(4):
            cx, cy = i*sq + (sq if False else 0), row*sq
            cx = i * sq + (0 if i < 8 else 0)
        for row in range(4):
            cx, cy = i*sq, row*sq
            dark = row in (1, 3)
            if dark: dither_dark(cx, cy)
            if dark: halo(cx, cy)
            blit(cx, cy, g if row < 2 else o)
    img = img.resize((img.width*scale, img.height*scale), Image.NEAREST)
    img.save(path)

def emit_c(path):
    lines = [f"// generated by gen_sprites.py: {S}x{S} masks, 1 bit per pixel",
             "// fill masks (black pieces) and outline masks (white pieces)",
             f"#define SPR {S}"]
    for kind, fn in (("FILL", lambda g: g), ("LINE", lambda g: outline(g))):
        for k in "PNBRQK":
            g = fn(parse(MASKS[k]))
            rows = []
            for y in range(S):
                v = 0
                for x in range(S):
                    if g[y][x]: v |= 1 << x
                rows.append(f"0x{v:05X}")
            lines.append(f"const uint32_t SPR_{kind}_{k}[SPR] = "
                         "{" + ",".join(rows) + "};")
    lines.append("const uint32_t* const SPR_FILL[6] = "
                 "{SPR_FILL_P,SPR_FILL_N,SPR_FILL_B,SPR_FILL_R,SPR_FILL_Q,SPR_FILL_K};")
    lines.append("const uint32_t* const SPR_LINE[6] = "
                 "{SPR_LINE_P,SPR_LINE_N,SPR_LINE_B,SPR_LINE_R,SPR_LINE_Q,SPR_LINE_K};")
    open(path, "w").write("\n".join(lines) + "\n")

